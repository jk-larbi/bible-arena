// Helper functions for character querying and game integration
export const characterServiceHelpers = {
  getAllCharacters(): BibleCharacterProfile[] {
    return ALL_BIBLE_CHARACTERS;
  },

  getCharacterById(id: string): BibleCharacterProfile | undefined {
    return ALL_BIBLE_CHARACTERS.find((c) => c.id === id);
  },

  getCharactersByTestament(testament: 'Old' | 'New'): BibleCharacterProfile[] {
    return ALL_BIBLE_CHARACTERS.filter((c) => c.testament === testament);
  },

  getCharactersByQuality(quality: string): BibleCharacterProfile[] {
    return ALL_BIBLE_CHARACTERS.filter((c) =>
      c.positiveQualities.some((q) => q.toLowerCase() === quality.toLowerCase())
    );
  },

  getAllCharacterQuestions(): CharacterLearningQuestion[] {
    return ALL_BIBLE_CHARACTERS.flatMap((c) => c.sampleQuestions);
  },
};
